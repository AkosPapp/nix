"""Ensure every enabled mautrix bridge's bot user exists on the homeserver - and that the DM
rooms it was force-joined into still count as management rooms (is_direct).

Since Synapse 1.162 checks the database (not just the appservice namespace) when an AS acts as
a user ("Application service has not registered this user"), a bot user that vanished with a
reprovisioned database deadlocks the bridge forever: its startup connection check runs as the
bot, fails with 403, and the registration call that would create the user is never reached.
Registering through /register with the bridge's own appservice token (type
m.login.application_service + inhibit_login, the only flow a MAS-enabled Synapse leaves open
to appservices) breaks that deadlock. Existing users answer M_USER_IN_USE and are fine.
"""

import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

HOMESERVER = os.environ["MATRIX_HOMESERVER"].rstrip("/")
# entries "<localpart>:<registration file>", repeated for every enabled bridge
BRIDGES = os.environ["BRIDGES"].split()
ADMIN_ID = os.environ["ADMIN_ID"]


def api(method, path, token, query=None, body=None):
    url = HOMESERVER + path
    if query:
        url += "?" + urllib.parse.urlencode(query)
    req = urllib.request.Request(
        url,
        data=json.dumps(body).encode() if body is not None else None,
        method=method,
        headers={"Authorization": "Bearer " + token, "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def fix_dm_flags(token, bot_id):
    """Re-mark rooms the bot was force-joined into as DMs.

    The bridge only treats a room as its management DM when the bot's own m.room.member event
    carries is_direct (a real invite carries it; an AS-forced join does not). Without it the
    bot sits in the room and silently drops every command. Rewriting the bot's join event with
    the flag through the appservice token makes the bridge adopt the room on the spot.
    """
    for room_id in api("GET", "/_matrix/client/v3/joined_rooms", token, {"user_id": bot_id}).get("joined_rooms", []):
        members = api("GET", "/_matrix/client/v3/rooms/%s/members" % urllib.parse.quote(room_id, safe=""),
                      token, {"membership": "join", "user_id": bot_id}).get("chunk", [])
        others = [ev["state_key"] for ev in members if ev["state_key"] != bot_id]
        if others != [ADMIN_ID]:
            continue  # not a one-on-one room with the admin
        mine = next((ev for ev in members if ev["state_key"] == bot_id), None)
        if mine and mine.get("content", {}).get("is_direct"):
            continue
        api("PUT", "/_matrix/client/v3/rooms/%s/state/m.room.member/%s" % (
            urllib.parse.quote(room_id, safe=""), urllib.parse.quote(bot_id, safe="")),
            token, {"user_id": bot_id}, {"membership": "join", "is_direct": True})
        print("marked %s as DM for %s" % (room_id, bot_id))


def as_token(reg_file):
    with open(reg_file) as f:
        for line in f:
            if line.startswith("as_token:"):
                return line.split(":", 1)[1].strip().strip("'\"")
    raise RuntimeError("no as_token in %s" % reg_file)


def register(localpart, reg_file):
    token = as_token(reg_file)
    body = json.dumps({
        "type": "m.login.application_service",
        "inhibit_login": True,
        "username": localpart,
    }).encode()
    req = urllib.request.Request(
        HOMESERVER + "/_matrix/client/v3/register",
        data=body,
        method="POST",
        headers={"Authorization": "Bearer " + token, "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            print("registered %s (%s)" % (localpart, json.load(resp).get("user_id")))
    except urllib.error.HTTPError as e:
        code = e.code
        err = ""
        try:
            err = json.loads(e.read()).get("errcode", "")
        except Exception:
            pass
        if err == "M_USER_IN_USE":
            print("%s already exists" % localpart)
        else:
            raise RuntimeError("%s: HTTP %d %s" % (localpart, code, err))


def main():
    failed = 0
    for entry in BRIDGES:
        localpart, reg_file = entry.split(":", 1)
        # The registration file is generated by the bridge's preStart; wait for it rather
        # than racing the activation transaction (files land within seconds, Synapse
        # migrations dominate the boot path anyway).
        for _ in range(90):
            if os.path.exists(reg_file):
                break
            time.sleep(2)
        else:
            print("no %s after 180s, skipping" % reg_file, file=sys.stderr)
            failed += 1
            continue
        try:
            register(localpart, reg_file)
            bot_id = "@%s:%s" % (localpart, ADMIN_ID.split(":", 1)[1])
            # The bot can only be queried as itself once it exists; its connection loop reaches
            # /versions with the very same token seconds later, so a short wait suffices.
            time.sleep(5)
            fix_dm_flags(as_token(reg_file), bot_id)
        except Exception as e:  # next boot / next manual run retries
            failed += 1
            print("failed: %s" % e, file=sys.stderr)
    # The bridge retry loops pick the bot up within their next 10s attempt; nothing to restart.
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
